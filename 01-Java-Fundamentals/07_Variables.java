/*
 * JAVA FUNDAMENTALS
 * CONCEPT: Variables
 *
 * What is it?
 * A variable is a named storage location used to hold a value.
 *
 * Why do we need it?
 * Variables let a program remember data and work with changing values.
 *
 * Simple real-world example:
 * A customer service may store a customer ID, name, or balance in variables.
 *
 * Important syntax / idea:
 * Syntax: dataType variableName = value;
 *
 * Key points:
 * - Understand the concept before memorizing syntax.
 * - Run the example and change the values to see what happens.
 * - Read the comments in the code; they explain the important parts.
 *
 * Interview note:
 * Be able to explain this concept in simple words and give one
 * practical example. Also understand the difference between similar
 * concepts where applicable.
 *
 * Example output:
 * The exact output depends on the values used in the program.
 */
class Concept07_Variables {
    public static void main(String[] args) {
        int age = 25;
        String name = "Omkar";

        System.out.println("Name: " + name);
        System.out.println("Age: " + age);
    }
}
