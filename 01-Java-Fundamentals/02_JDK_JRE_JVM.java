/*
 * JAVA FUNDAMENTALS
 * CONCEPT: JDK vs JRE vs JVM
 *
 * What is it?
 * JDK is the development kit, JRE provides the runtime environment, and JVM executes Java bytecode.
 *
 * Why do we need it?
 * A developer needs the JDK because it contains tools such as javac. A user running a Java application needs the runtime components.
 *
 * Simple real-world example:
 * Think of the JDK as a workshop, the JRE as the place containing what is needed to run the program, and the JVM as the engine.
 *
 * Important syntax / idea:
 * JDK -> tools + runtime components -> JVM -> executes bytecode.
 *
 * Key points:
 * - Understand the concept before memorizing syntax.
 * - Run the example and change the values to see what happens.
 * - Read the comments in the code; they explain the important parts.
 *
 * Interview note:
 * Be able to explain this concept in simple words and give one
 * practical example. Also understand the difference between similar
 * concepts where applicable.
 *
 * Example output:
 * The exact output depends on the values used in the program.
 */
class Concept02_JDK_JRE_JVM {
    public static void main(String[] args) {
        System.out.println("JDK: used to develop Java applications");
        System.out.println("JRE: provides the runtime environment");
        System.out.println("JVM: executes Java bytecode");
    }
}
