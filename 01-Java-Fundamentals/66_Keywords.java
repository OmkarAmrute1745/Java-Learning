/*
 * JAVA FUNDAMENTALS
 * CONCEPT: Java Keywords
 *
 * What is it?
 * Keywords are reserved words that have special meaning in Java.
 *
 * Why do we need it?
 * They form the language syntax and cannot be used as ordinary identifiers.
 *
 * Simple real-world example:
 * Examples include class, public, static, final, if, else, return, and new.
 *
 * Important syntax / idea:
 * Do not try to use a keyword as a variable or class name.
 *
 * Key points:
 * - Understand the concept before memorizing syntax.
 * - Run the example and change the values to see what happens.
 * - Read the comments in the code; they explain the important parts.
 *
 * Interview note:
 * Be able to explain this concept in simple words and give one
 * practical example. Also understand the difference between similar
 * concepts where applicable.
 *
 * Example output:
 * The exact output depends on the values used in the program.
 */
class Concept66_Keywords {
    public static void main(String[] args) {
        final int age = 25;
        if (age >= 18) {
            System.out.println("adult");
        }

        // class, if, final, and return are examples of Java keywords.
    }
}
